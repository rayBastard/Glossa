// Copies third-party libraries and fonts into web/vendor so the app works
// fully offline and the iOS build never loads code from the network.
import { cpSync, mkdirSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const nm = "node_modules";
const out = "web/vendor";
mkdirSync(join(out, "fonts"), { recursive: true });

const copy = (from, to) => {
  if (!existsSync(from)) { console.error(`missing ${from} — run "npm install" first`); process.exit(1); }
  cpSync(from, to);
};

copy(join(nm, "pdfjs-dist/build/pdf.min.js"), join(out, "pdf.min.js"));
copy(join(nm, "pdfjs-dist/build/pdf.worker.min.js"), join(out, "pdf.worker.min.js"));
copy(join(nm, "jszip/dist/jszip.min.js"), join(out, "jszip.min.js"));

// Fonts: Literata (book text) and Manrope (interface), latin + latin-ext + cyrillic.
const fonts = [
  { pkg: "@fontsource/literata", family: "Literata", weights: [400, 600], italic: [400] },
  { pkg: "@fontsource/manrope", family: "Manrope", weights: [400, 500, 600, 700], italic: [] },
];
const subsets = ["latin", "latin-ext", "cyrillic", "cyrillic-ext", "greek", "vietnamese"];
let css = "/* generated by scripts/vendor.mjs */\n";
for (const f of fonts) {
  const dir = join(nm, f.pkg, "files");
  const files = readdirSync(dir).filter(n => n.endsWith(".woff2"));
  for (const subset of subsets) {
    for (const [style, ws] of [["normal", f.weights], ["italic", f.italic]]) {
      for (const w of ws) {
        const name = files.find(n => n === `${f.pkg.split("/")[1]}-${subset}-${w}-${style}.woff2`);
        if (!name) continue;
        cpSync(join(dir, name), join(out, "fonts", name));
        css += `@font-face{font-family:'${f.family}';font-style:${style};font-weight:${w};font-display:swap;src:url(fonts/${name}) format('woff2')}\n`;
      }
    }
  }
}
writeFileSync(join(out, "fonts.css"), css);
console.log("vendor: ok →", out);
